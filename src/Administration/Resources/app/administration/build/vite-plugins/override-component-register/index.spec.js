/**
 * @sw-package framework
 */
import OverrideComponentRegisterPlugin from './index';
import path from 'path';

describe('build/vite-plugins/override-component-register', () => {
    it('should be a function with 1 optional argument', () => {
        expect(typeof OverrideComponentRegisterPlugin).toBe('function');

        // check that the function takes 1 argument
        expect(OverrideComponentRegisterPlugin).toHaveLength(1);
    });

    it('should return an object with a name, configResolved and transform property', () => {
        const plugin = OverrideComponentRegisterPlugin({
            root: 'root',
            pluginEntryFile: 'plugin',
        });

        // Identify plugin by name
        expect(plugin).toHaveProperty('name');
        expect(plugin.name).toBe('shopware-vite-plugin-override-component');

        // Check if the plugin has all methods
        expect(plugin).toHaveProperty('configResolved');
        expect(plugin).toHaveProperty('transform');
    });

    it('should return null if transform is called without calling configResolved', () => {
        const plugin = OverrideComponentRegisterPlugin({
            root: 'root',
            pluginEntryFile: 'plugin',
        });

        const result = plugin.transform('code', 'id');

        expect(result).toBeNull();
    });

    it('should transform entry file correctly', () => {
        const plugin = OverrideComponentRegisterPlugin({
            root: path.resolve(__dirname, './_fixtures'),
            pluginEntryFile: 'plugin',
        });

        // Call configResolved to find all override files
        plugin.configResolved();

        const mainEntryCode = `
            import { createApp } from 'vue';
            import App from './App.vue';
            import './assets/style.scss';

            createApp(App).mount('#app');
        `;

        const result = plugin.transform(mainEntryCode, 'plugin');

        // Check if the code was transformed correctly
        expect(result).toHaveProperty('code');
        expect(result.code).toContain('/* Start: auto generated by Shopware */');
        expect(result.code).toContain(
            "import _build_vite_plugins_override_component_register__fixtures_sw_spec_foo from './build/vite-plugins/override-component-register/_fixtures/sw-spec_foo.override.vue';",
        );
        expect(result.code).toContain(
            'Shopware.Component.registerOverrideComponent(_build_vite_plugins_override_component_register__fixtures_sw_spec_foo);',
        );
        expect(result.code).toContain(
            "import _build_vite_plugins_override_component_register__fixtures_sw_setup_example from './build/vite-plugins/override-component-register/_fixtures/sw-setup-example.override.vue';",
        );
        expect(result.code).toContain(
            'Shopware.Component.registerOverrideComponent(_build_vite_plugins_override_component_register__fixtures_sw_setup_example);',
        );
        expect(result.code).toContain('/* End: auto generated by Shopware */');
    });

    it('keeps import identifiers unique for same-named overrides in different directories', () => {
        const plugin = OverrideComponentRegisterPlugin({
            root: path.resolve(__dirname, './_fixtures'),
            pluginEntryFile: 'plugin',
        });

        plugin.configResolved();

        const result = plugin.transform('// entry', 'plugin');

        // Several overrides of the same component share a basename (first/sw-thing.override.vue,
        // second/sw-thing.override.vue); the generated identifiers must not collide.
        const identifiers = [...result.code.matchAll(/import (\S+) from/g)].map((match) => match[1]);

        expect(new Set(identifiers).size).toBe(identifiers.length);
        expect(identifiers.length).toBeGreaterThanOrEqual(4);
    });
});
