import type { Plugin } from 'vite';

type Options = {
    pluginEntryFile: string;
};

/**
 * @sw-package framework
 * @private - Only to be used by shopware directly
 *
 * Creates a Vite plugin that registers all *.override.vue files below the Vite root
 * in the bundle entry file.
 */
export default function viteOverridePlugin(options: Options): Plugin {
    const { pluginEntryFile } = options;

    return {
        name: 'shopware-vite-plugin-override-component',

        transform(code, id) {
            if (id !== pluginEntryFile) {
                return null;
            }

            // Vite expands the glob in sorted file order and reloads the entry when a matching file is added or deleted.
            return {
                code: `
                /* Start: auto generated by Shopware */
                Object.values(import.meta.glob('/**/*.override.vue', { eager: true, import: 'default' }))
                    .forEach((component) => Shopware.Component.registerOverrideComponent(component));
                /* End: auto generated by Shopware */

                ${code}`,
                map: null,
            };
        },
    };
}
