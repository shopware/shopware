import path from 'path';
import type { Plugin } from 'vite';
import { findFilesRecursively } from '../utils';

type Options = {
    root: string;
    pluginEntryFile: string;
};

/**
 * @sw-package framework
 * @private - Only to be used by shopware directly
 *
 * Creates a Vite plugin that automatically imports all *.override.vue files
 * into the bundle entry file.
 */
export default function viteOverridePlugin(options: Options): Plugin {
    const { root, pluginEntryFile } = options;
    const pattern = /\.override\.vue$/;

    let overrideFiles = [] as string[];

    /**
     * Lists every override file below `root`. Sorted because the walk follows filesystem order, which differs
     * between machines - and the generated entry numbers its imports in this order.
     */
    function scanOverrideFiles(): string[] {
        return findFilesRecursively(root, pattern).sort();
    }

    return {
        name: 'shopware-vite-plugin-override-component',

        configResolved() {
            overrideFiles = scanOverrideFiles();
        },

        configureServer(server) {
            const client = server.environments.client;

            // The entry only imports the overrides found by the last scan, so adding or deleting one
            // has to regenerate the entry and reload the page that already evaluated the old one.
            const onOverrideFileAddedOrRemoved = (file: string) => {
                if (!pattern.test(file)) {
                    return;
                }

                const rescannedFiles = scanOverrideFiles();

                if (rescannedFiles.join('\n') === overrideFiles.join('\n')) {
                    return;
                }

                overrideFiles = rescannedFiles;

                const entryModule = client.moduleGraph.getModuleById(pluginEntryFile);

                if (!entryModule) {
                    return;
                }

                client.moduleGraph.invalidateModule(entryModule);
                client.hot.send({ type: 'full-reload' });
            };

            // The watcher closes together with the server, which drops these listeners.
            /* eslint-disable listeners/no-missing-remove-event-listener */
            server.watcher.on('add', onOverrideFileAddedOrRemoved);
            server.watcher.on('unlink', onOverrideFileAddedOrRemoved);
            /* eslint-enable listeners/no-missing-remove-event-listener */
        },

        transform(code, id) {
            // Only transform the entry file
            if (id !== pluginEntryFile || overrideFiles.length === 0) {
                return null;
            }

            const componentNames = [] as string[];

            // Generate import statements for each override file
            const imports = overrideFiles
                .map((file, index) => {
                    // Convert absolute path to relative path from entry file
                    const relativePath = path.relative(path.dirname(id), file);

                    // Ensure proper path separators
                    const importPath = relativePath.split(path.sep).join('/');

                    // Numbered, not path-derived: `foo-bar/sw-x` and `foo_bar/sw-x` sanitize to one name.
                    const componentName = `_swOverride${index}`;
                    componentNames.push(componentName);

                    return `import ${componentName} from './${importPath}';`;
                })
                .join('\n');

            const registers = componentNames
                .map((name) => {
                    return `Shopware.Component.registerOverrideComponent(${name});`;
                })
                .join('\n');

            // Add imports at the beginning of the file
            return {
                code: `
                /* Start: auto generated by Shopware */\n
                ${imports}\n${registers}\n
                /* End: auto generated by Shopware */\n\n
                ${code}`,
                map: null,
            };
        },
    };
}
