import fs from 'fs';
import path from 'path';
import type { Plugin } from 'vite';
import { findFilesRecursively } from '../utils';

type Options = {
    root: string;
    pluginEntryFile: string;
};

/**
 * Matches the static `extends` identity of a `<sw-block extends="...">` element.
 *
 * A regex is sufficient because the setup transform rejects every other form: `extends` must be a
 * static attribute, so there is no bound or computed value that a parser would have to resolve.
 */
const SW_BLOCK_EXTENDS_REG_EXP = /<sw-block\s[^>]*?extends\s*=\s*"([^"]+)"/g;

/**
 * Collects the block names the override files extend.
 *
 * The names have to be known at module import time - the administration renders every Twig component
 * template during boot, and only a block announced by then can be materialized as a `<sw-block>`
 * element for a native override to reach into.
 */
function collectExtendedBlockNames(files: string[]): string[] {
    const blockNames = new Set<string>();

    files.forEach((file) => {
        const source = fs.readFileSync(file, 'utf8').replace(/<!--[\s\S]*?-->/g, '');

        for (const match of source.matchAll(SW_BLOCK_EXTENDS_REG_EXP)) {
            blockNames.add(match[1]);
        }
    });

    return Array.from(blockNames).sort();
}

/**
 * @sw-package framework
 * @private - Only to be used by shopware directly
 *
 * Creates a Vite plugin that automatically imports all *.override.vue files
 * into the bundle entry file.
 */
export default function viteOverridePlugin(options: Options): Plugin {
    const { root, pluginEntryFile } = options;
    const pattern = /\.override\.vue$/;

    let overrideFiles = [] as string[];
    let extendedBlockNames = [] as string[];

    return {
        name: 'shopware-vite-plugin-override-component',

        configResolved() {
            // Find all override files. Sorted because the directory walk follows filesystem order, which
            // differs between machines - and the generated entry numbers its imports in this order, so
            // sorting is what keeps the emitted source byte-stable across builds.
            overrideFiles = findFilesRecursively(root, pattern).sort();
            extendedBlockNames = collectExtendedBlockNames(overrideFiles);
        },

        transform(code, id) {
            // Only transform the entry file
            if (id !== pluginEntryFile || overrideFiles.length === 0) {
                return null;
            }

            const componentNames = [] as string[];

            // Generate import statements for each override file
            const imports = overrideFiles
                .map((file, index) => {
                    // Convert absolute path to relative path from entry file
                    const relativePath = path.relative(path.dirname(id), file);

                    // Ensure proper path separators
                    const importPath = relativePath.split(path.sep).join('/');

                    // Numbered, not path-derived: `foo-bar/sw-x` and `foo_bar/sw-x` sanitize to one name.
                    const componentName = `_swOverride${index}`;
                    componentNames.push(componentName);

                    return `import ${componentName} from './${importPath}';`;
                })
                .join('\n');

            const registers = componentNames
                .map((name) => {
                    return `Shopware.Component.registerOverrideComponent(${name});`;
                })
                .join('\n');

            // Announced before the imports run: a Twig component only materializes the block boundaries
            // listed here, and it renders its template during boot, before any override component mounts.
            const blockRegistration =
                extendedBlockNames.length > 0
                    ? `Shopware.Component.registerNativeBlockOverrides(${JSON.stringify(extendedBlockNames)});\n`
                    : '';

            // Add imports at the beginning of the file
            return {
                code: `
                /* Start: auto generated by Shopware */\n
                ${blockRegistration}${imports}\n${registers}\n
                /* End: auto generated by Shopware */\n\n
                ${code}`,
                map: null,
            };
        },
    };
}
