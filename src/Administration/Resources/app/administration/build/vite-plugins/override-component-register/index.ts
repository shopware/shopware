import path from 'path';
import MagicString from 'magic-string';
import type { Plugin } from 'vite';
import { findFilesRecursively } from '../utils';

type Options = {
    root: string;
    pluginEntryFile: string;
};

/**
 * @sw-package framework
 * @private - Only to be used by shopware directly
 *
 * Imports every *.override.vue file of an extension from its entry file. Importing an override
 * registers its setup callback; the hidden-mount registration below is what renders its
 * `<sw-block extends>` template content.
 */
export default function viteOverridePlugin(options: Options): Plugin {
    const { root, pluginEntryFile } = options;

    let overrideFiles = [] as string[];

    return {
        name: 'shopware-vite-plugin-override-component',

        configResolved() {
            // Sorted because the generated entry numbers its imports in this order, and the directory
            // walk follows filesystem order, which differs between machines.
            overrideFiles = findFilesRecursively(root, /\.override\.vue$/).sort();
        },

        transform(code, id) {
            if (id !== pluginEntryFile || overrideFiles.length === 0) {
                return null;
            }

            // Numbered, not path-derived: `foo-bar/sw-x` and `foo_bar/sw-x` would sanitize to one name.
            const bindings = overrideFiles.map((_, index) => `_swOverride${index}`);
            const imports = overrideFiles.map((file, index) => {
                const importPath = path.relative(path.dirname(id), file).split(path.sep).join('/');

                return `import ${bindings[index]} from './${importPath}';`;
            });
            const registers = bindings.map((binding) => `Shopware.Component.registerOverrideComponent(${binding});`);
            const output = new MagicString(code).prepend(
                [
                    '/* Start: auto generated by Shopware */',
                    ...imports,
                    ...registers,
                    '/* End: auto generated by Shopware */',
                    '',
                ].join('\n'),
            );

            return {
                code: output.toString(),
                map: output.generateMap({ hires: true, source: id }),
            };
        },
    };
}
