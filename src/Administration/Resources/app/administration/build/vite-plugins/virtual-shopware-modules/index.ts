/**
 * @sw-package framework
 */

import fs from 'node:fs';
import path from 'node:path';
import type { Plugin } from 'vite';
import {
    allSpecifiers,
    defaultExpression,
    exportNames,
    memberExpression,
    parseSpecifier,
    type ModuleRegistry,
} from './definitions';

type Options = {
    /** Root of the Administration package, i.e. the directory holding `src/` and `package.json`. */
    administrationRoot: string;
    /**
     * Where the generated modules get the `Shopware` object.
     *
     * `host` is the Administration's own build, which imports the instance and so cannot run before it
     * exists. `extension` is a plugin build, whose bundle has no access to Administration source and
     * reads the global the host already assigned.
     */
    consumer: Consumer;
};

/** @private */
export type Consumer = 'host' | 'extension';

/** Rollup convention: a leading NUL marks an id no other plugin should touch or read from disk. */
const RESOLVED_PREFIX = '\0';

const REGISTRY_FILE = 'shopware-modules.json';

/**
 * @private
 *
 * The checked-in registry of every `shopware:*` specifier.
 *
 * The build reads this rather than parsing the Administration sources, so adding a utility, mixin or
 * store shows up as a diff in a pull request instead of silently changing what resolves.
 * `composer admin:generate-shopware-modules` rewrites it.
 */
export function readRegistry(administrationRoot: string): ModuleRegistry {
    const file = path.join(administrationRoot, REGISTRY_FILE);

    return JSON.parse(fs.readFileSync(file, 'utf8')) as ModuleRegistry;
}

/** @private Re-exported so the Vite plugin and the Jest setup reach the whole contract from one module. */
export { allSpecifiers, exportNames };

/**
 * How a generated module gets hold of the `Shopware` object.
 *
 * The host imports it, which is what makes these modules safe anywhere: a static import is evaluated
 * before the module that needs it, so there is no moment when the instance is missing. A mixin subpath
 * imports the mixin registry for the same reason — the registry is an eager glob, so importing it
 * registers every mixin it owns before the lookup below runs.
 *
 * An extension bundle cannot import Administration source, so it reads the global the host assigned.
 * Extension code always runs after boot, and the guard says so if that ever stops being true.
 */
function preamble(parsed: ParsedSpecifier, consumer: Consumer): string[] {
    if (consumer === 'host') {
        return [
            ...(parsed.family === 'shopware:mixins' ? ["import 'src/app/mixin';"] : []),
            "import { ShopwareInstance as shopware } from 'src/core/shopware';",
        ];
    }

    const tooEarly =
        'The global Shopware object did not exist yet. An extension bundle is loaded after the ' +
        'Administration has booted, so this should be unreachable.';

    return [
        'const shopware = globalThis.Shopware;',
        'if (!shopware) {',
        `    throw new Error(${JSON.stringify(tooEarly)});`,
        '}',
    ];
}

/**
 * @private
 *
 * The source of one `shopware:*` module.
 *
 * A flat list of `export const` bindings rather than one namespace object: Rollup only tree-shakes and
 * validates what it sees statically, so a mistyped import fails the build instead of becoming
 * `undefined` at runtime. Namespace subpaths expose the same object as their default and through explicit
 * named exports, so `import debug, { warn } from 'shopware:utils/debug'` works.
 */
export function generateModuleSource(
    specifier: string,
    registry: ModuleRegistry,
    consumer: Consumer = 'host',
): string | undefined {
    const parsed = parseSpecifier(specifier);
    const members = parsed && exportNames(registry, parsed);

    if (!parsed || !members) {
        return undefined;
    }

    return [
        `// Generated by build/vite-plugins/virtual-shopware-modules for "${specifier}".`,
        ...preamble(parsed, consumer),
        '',
        ...members.map((member) => `export const ${member} = ${memberExpression(parsed, member)};`),
        '',
        `export default ${defaultExpression(parsed)};`,
        '',
    ].join('\n');
}

/**
 * @private
 *
 * Serves the `shopware:*` modules, which expose the global `Shopware` object as ordinary imports:
 * `import { createId } from 'shopware:utils'` instead of `Shopware.Utils.createId`.
 *
 * Utility, data, and mixin bindings capture their values during module evaluation. Store modules defer
 * the registry lookup until the exported function runs. Extension builds use the host registry.
 */
export default function virtualShopwareModulesPlugin(options: Options): Plugin {
    let registry: ModuleRegistry | undefined;

    const registryFile = path.join(options.administrationRoot, REGISTRY_FILE);
    const load = (): ModuleRegistry => {
        registry ??= readRegistry(options.administrationRoot);

        return registry;
    };

    return {
        name: 'shopware-virtual-modules',

        resolveId(id) {
            const parsed = parseSpecifier(id);

            if (!parsed || !exportNames(load(), parsed)) {
                return null;
            }

            return `${RESOLVED_PREFIX}${id}`;
        },

        load(id) {
            if (!id.startsWith(RESOLVED_PREFIX)) {
                return null;
            }

            const source = generateModuleSource(id.slice(RESOLVED_PREFIX.length), load(), options.consumer);

            if (source === undefined) {
                return null;
            }

            // A new specifier only exists once the registry is regenerated, so the dev server has to
            // notice that file changing.
            this.addWatchFile(registryFile);

            return source;
        },

        handleHotUpdate({ file, server }) {
            if (file !== registryFile) {
                return;
            }

            registry = undefined;

            const virtualModules = [...server.moduleGraph.idToModuleMap.values()].filter((module) =>
                module.id?.startsWith(`${RESOLVED_PREFIX}shopware:`),
            );

            virtualModules.forEach((module) => server.moduleGraph.invalidateModule(module));

            return virtualModules;
        },
    };
}
