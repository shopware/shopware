/**
 * @sw-package framework
 *
 * Covers what an override template is *not* allowed to author.
 *
 * Two families: bindings the transform owns on `<sw-block>` (`data`, `#default`, `v-bind` objects,
 * a bound `:extends`), and structural rules for override templates (only `<sw-block extends>` at the
 * top level, no writes to forwarded override locals). Forwarding lives in `override-template.spec.ts`.
 */

import { stripIndent, transformOrFail, transformShopwareSetupSfc } from './helpers';
import { ShopwareSetupTransformError } from '../utils/transform-error';

function getDirectNamedSlotDiagnostic(source: string, filename: string): ShopwareSetupTransformError {
    let thrown: unknown;

    try {
        transformShopwareSetupSfc(source, filename);
    } catch (error) {
        thrown = error;
    }

    if (!(thrown instanceof ShopwareSetupTransformError)) {
        throw new Error('Expected a direct named-slot diagnostic.');
    }

    return thrown;
}

describe('build/vue-setup-transform override template guards', () => {
    it.each([
        '#footer',
        '#[slotName]',
        'v-slot:footer',
        'v-slot:[slotName]',
    ])('rejects a direct non-default named slot %s on an override sw-block', (slotDirective) => {
        const source = stripIndent`
            <template>
            <sw-block extends="sw_example_component_body">
                <template ${slotDirective}>content</template>
            </sw-block>
            </template>
            <script setup>
            const slotName = 'footer';

            swDefineOverride({});
            </script>
        `;

        const diagnostic = getDirectNamedSlotDiagnostic(source, 'override-direct-named-slot.override.vue');

        expect(diagnostic.message).toContain('A direct non-default named slot below <sw-block> is not supported.');
        expect(diagnostic.index).toBe(source.indexOf(`<template ${slotDirective}>`));
    });

    it('rejects authored data bindings on extended sw-blocks', () => {
        const source = stripIndent`
            <template>
            <sw-block extends="sw_example_component_body" :data="scope">
                <p>{{ info }}</p>
            </sw-block>
            </template>
            <script setup>
            const scope = {};
            const info = 'local';

            swDefineOverride({});
            </script>
        `;

        expect(() => transformOrFail(source, 'authored-data.override.vue')).toThrow(
            'The data binding of <sw-block> is generated by the Shopware setup transform and must not be authored.',
        );
    });

    it('rejects v-bind objects on extended sw-blocks', () => {
        const source = stripIndent`
            <template>
            <sw-block extends="sw_example_component_body" v-bind="attrs">
                <p>{{ info }}</p>
            </sw-block>
            </template>
            <script setup>
            const attrs = {};
            const info = 'local';

            swDefineOverride({});
            </script>
        `;

        expect(() => transformOrFail(source, 'authored-v-bind.override.vue')).toThrow('"v-bind" is not supported');
    });

    it('rejects writing to a forwarded binding from sw-block extends content', () => {
        const source = stripIndent`
            <template>
            <sw-block extends="sw_example_component_body">
                <button @click="count = count + 1">inc</button>
            </sw-block>
            </template>
            <script setup>
            import { ref } from 'vue';

            const count = ref(0);

            swDefineOverride({ count });
            </script>
        `;

        // The forwarded `count` arrives ref-unwrapped as a slot-scope local, so the assignment silently
        // no-ops (the identical line works in a base component). Reject it loudly.
        expect(() => transformOrFail(source, 'forwarded-write.override.vue')).toThrow(
            'Cannot assign to "count" inside <sw-block extends> content',
        );
    });

    it('rejects an update expression (count++) on a forwarded binding', () => {
        const source = stripIndent`
            <template>
            <sw-block extends="sw_example_component_body">
                <button @click="count++">inc</button>
            </sw-block>
            </template>
            <script setup>
            import { ref } from 'vue';

            const count = ref(0);

            swDefineOverride({ count });
            </script>
        `;

        expect(() => transformOrFail(source, 'forwarded-update.override.vue')).toThrow(
            'Cannot assign to "count" inside <sw-block extends> content',
        );
    });

    it.each([
        ['a destructuring assignment', '@click="[count] = [1]"'],
        ['an interpolation', '{{ count++ }}'],
        ['an input alias', '@click="previousState = null"'],
    ])('rejects writing to an override local through %s', (_name, write) => {
        const source = stripIndent`
            <template>
            <sw-block extends="sw_example_component_body">
                <button ${write.startsWith('@') ? write : ''}>${write.startsWith('@') ? '' : write}</button>
            </sw-block>
            </template>
            <script setup>
            const previousState = useSwPreviousState();
            const count = 0;

            swDefineOverride({});
            </script>
        `;

        expect(() => transformOrFail(source, 'forwarded-write-forms.override.vue')).toThrow(
            /Cannot assign to "(count|previousState)" inside <sw-block extends> content/,
        );
    });

    it('allows writes to template locals and JS locals that shadow an override local', () => {
        const source = stripIndent`
            <template>
            <sw-block extends="sw_example_component_body">
                <p v-for="count in rows" @click="count = 1">{{ count }}</p>
                <Child #default="{ count }"><button @click="count++">inc</button></Child>
                <button @click="((count) => { count = 2; })(0)">local</button>
            </sw-block>
            </template>
            <script setup>
            const count = 0;
            const rows = [];

            swDefineOverride({});
            </script>
        `;

        expect(transformOrFail(source, 'shadowed-writes.override.vue').code).toContain(
            '#default="{ __swOverride: { [__swSetupNamespace]: { count, rows } = {} } = {} }"',
        );
    });

    it('points the write rejection at the writing expression', () => {
        const source = stripIndent`
            <template>
            <sw-block extends="sw_example_component_body">
                <button @click="count = 1">inc</button>
            </sw-block>
            </template>
            <script setup>
            const count = 0;

            swDefineOverride({});
            </script>
        `;

        let thrown: unknown;

        try {
            transformShopwareSetupSfc(source, 'write-offset.override.vue');
        } catch (error) {
            thrown = error;
        }

        expect((thrown as ShopwareSetupTransformError).index).toBe(source.indexOf('count = 1'));
    });

    it('rejects a bound :extends on sw-block (only a static extends is allowed)', () => {
        const source = stripIndent`
            <template>
            <sw-block :extends="blockName">
                <p>{{ body }}</p>
            </sw-block>
            </template>
            <script setup>
            const blockName = 'sw_example_component_body';
            const body = 'local';

            swDefineOverride({});
            </script>
        `;

        expect(() => transformOrFail(source, 'bound-extends.override.vue')).toThrow(
            'Only a static "extends" attribute is allowed on <sw-block>; ":extends" is not supported.',
        );
    });

    it('rejects an authored #default supplied through a child <template>', () => {
        const source = stripIndent`
            <template>
            <sw-block extends="sw_example_component_body">
                <template #default="{ body }">
                    <p>{{ body }}</p>
                </template>
            </sw-block>
            </template>
            <script setup>
            swDefineOverride({});
            </script>
        `;

        // The generated #default is injected on the element, so a child <template #default> must be
        // rejected with the same message instead of colliding into an opaque Vue codegen error.
        expect(() => transformOrFail(source, 'child-template-default.override.vue')).toThrow(
            'The default slot scope of <sw-block> is generated by the Shopware setup transform and must not be authored.',
        );
    });

    it('rejects top-level override content that is not a sw-block extends block', () => {
        const source = stripIndent`
            <template>
            <sw-block extends="sw_example_component_body">
                <p>{{ body }}</p>
            </sw-block>
            <div>{{ stray }}</div>
            </template>
            <script setup>
            const body = 'x';
            const stray = 'y';

            swDefineOverride({});
            </script>
        `;

        // An override renders only inside the blocks it extends; a top-level <div> would never render.
        expect(() => transformOrFail(source, 'stray-top-level.override.vue')).toThrow(
            'An override template may only contain <sw-block extends="..."> blocks at its top level.',
        );
    });

    it('rejects a base-style named sw-block nested inside an override extends block', () => {
        const source = stripIndent`
            <template>
            <sw-block extends="sw_example_component_body">
                <sw-block name="sw_new_block">
                    <p>content</p>
                </sw-block>
            </sw-block>
            </template>
            <script setup>
            swDefineOverride({});
            </script>
        `;

        expect(() => transformOrFail(source, 'nested-named-block.override.vue')).toThrow(
            '<sw-block name="..."> is only valid in a base component.',
        );
    });

    it('rejects a base-style named sw-block at the top level of an override', () => {
        const source = stripIndent`
            <template>
            <sw-block name="sw_new_block">
                <p>content</p>
            </sw-block>
            </template>
            <script setup>
            swDefineOverride({});
            </script>
        `;

        expect(() => transformOrFail(source, 'top-level-named-block.override.vue')).toThrow(
            'An override template may only contain <sw-block extends="..."> blocks at its top level.',
        );
    });

    it('rejects directives on the sw-block extends element itself', () => {
        const source = stripIndent`
            <template>
            <sw-block extends="sw_example_component_body" v-if="showOverride">
                <p>text</p>
            </sw-block>
            </template>
            <script setup>
            import { ref } from 'vue';

            const showOverride = ref(true);

            swDefineOverride({});
            </script>
        `;

        // The generated slot scope only exists inside the block, so `showOverride` on the element itself
        // resolves against the hidden component and the block never mounts - reject it loudly instead.
        expect(() => transformOrFail(source, 'extends-element-directive.override.vue')).toThrow('"v-if" is not supported');
    });
});
