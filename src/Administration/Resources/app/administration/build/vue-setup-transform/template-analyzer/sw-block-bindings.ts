/**
 * Owns the generated bindings of `<sw-block>` elements.
 *
 * The transform generates the block's `data` binding (base mode). Authoring it, a `#default` scope, or a
 * `v-bind` object that could carry either is rejected, so what a block receives is exactly what was wired.
 */

import { NodeTypes, type TemplateChildNode } from '@vue/compiler-dom';
import type { ShopwareSetupMode } from '../utils/shopware-setup-block';
import { ShopwareSetupTransformError } from '../utils/transform-error';
import { type DirectiveNode, type ElementNode, getDefaultSlotDirective, isSwBlockExtends } from './template-references';

function getDirectNamedSlot(node: ElementNode): ElementNode | undefined {
    for (const child of node.children) {
        if (child.type !== NodeTypes.ELEMENT || child.tag !== 'template') {
            continue;
        }

        const directive = child.props.find(
            (prop): prop is DirectiveNode =>
                prop.type === NodeTypes.DIRECTIVE &&
                (prop as DirectiveNode).name === 'slot' &&
                !(
                    !(prop as DirectiveNode).arg ||
                    ((prop as DirectiveNode).arg?.isStatic && (prop as DirectiveNode).arg?.content === 'default')
                ),
        );

        if (directive) {
            return child as ElementNode;
        }
    }

    return undefined;
}

/**
 * Enforces the strict `<sw-block>` attribute contract.
 *
 * `<sw-block>` renders its content as a fragment (its `render()` returns the block content, with no root
 * element), so a fallthrough attribute like `class` has no DOM node to land on, and a directive/binding
 * would resolve against the wrong component. The only attribute allowed is therefore a **static**
 * identity: `name` in base mode, `extends` in override mode. The transform-generated `data`/`#default`
 * bindings and the wrong-mode identity get targeted messages; everything else (other attributes,
 * directives, bound identity, `v-bind` objects) is rejected as unsupported.
 */
function assertSwBlockAttributes(node: ElementNode, mode: ShopwareSetupMode, templateOffset: number): void {
    const identityAttr = mode === 'base' ? 'name' : 'extends';
    const wrongIdentityAttr = mode === 'base' ? 'extends' : 'name';

    // `#default` authored on the element, or via a direct child `<template #default>` (which would
    // otherwise slip past and make Vue fail with an opaque "Codegen node is missing" error).
    const authoredDefaultSlot =
        getDefaultSlotDirective(node) ??
        node.children.find(
            (child): child is ElementNode =>
                child.type === NodeTypes.ELEMENT &&
                child.tag === 'template' &&
                Boolean(getDefaultSlotDirective(child as ElementNode)),
        );

    if (authoredDefaultSlot) {
        throw new ShopwareSetupTransformError(
            'The default slot scope of <sw-block> is generated by the Shopware setup transform and must not be ' +
                'authored. Reference setup bindings directly instead.',
            templateOffset + authoredDefaultSlot.loc.start.offset,
        );
    }

    const directNamedSlot = getDirectNamedSlot(node);

    if (directNamedSlot) {
        throw new ShopwareSetupTransformError(
            'A direct non-default named slot below <sw-block> is not supported. <sw-block> forwards only its ' +
                'default slot; move the <sw-block> inside the named-slot template.',
            templateOffset + directNamedSlot.loc.start.offset,
        );
    }

    node.props.forEach((prop) => {
        const directive = prop.type === NodeTypes.DIRECTIVE ? (prop as DirectiveNode) : null;
        const attributeName = prop.type === NodeTypes.ATTRIBUTE ? prop.name : null;
        const boundArg = directive?.name === 'bind' && directive.arg?.isStatic ? directive.arg.content : null;

        // The one allowed attribute: a static identity for this mode.
        if (attributeName === identityAttr) {
            return;
        }

        // Wrong-mode identity (static or bound).
        if (attributeName === wrongIdentityAttr || boundArg === wrongIdentityAttr) {
            throw new ShopwareSetupTransformError(
                mode === 'base'
                    ? '<sw-block extends="..."> is only valid in an override component. A base component declares ' +
                      'blocks with <sw-block name="...">.'
                    : '<sw-block name="..."> is only valid in a base component. An override contributes into an ' +
                      'existing block with <sw-block extends="...">.',
                templateOffset + prop.loc.start.offset,
            );
        }

        // The transform-generated data binding.
        if (attributeName === 'data' || boundArg === 'data') {
            throw new ShopwareSetupTransformError(
                'The data binding of <sw-block> is generated by the Shopware setup transform and must not be authored.',
                templateOffset + prop.loc.start.offset,
            );
        }

        // Everything else - class, other directives, a bound identity, a v-bind object.
        const label = directive ? (directive.rawName ?? `v-${directive.name}`) : (attributeName ?? 'binding');
        throw new ShopwareSetupTransformError(
            `Only a static "${identityAttr}" attribute is allowed on <sw-block>; "${label}" is not supported. ` +
                'sw-block renders its content as a fragment, so other attributes have no effect and their bindings ' +
                'would resolve against the wrong component.',
            templateOffset + prop.loc.start.offset,
        );
    });
}

/**
 * Rejects any top-level override template content that is not a `<sw-block extends>` block.
 *
 * An override `.vue` file fundamentally represents "the extension points of a component": it only
 * renders inside the blocks it extends (its hidden boot component has no template of its own that the
 * app shows). So any other top-level markup - plain elements, text, interpolations, or a `<sw-block
 * name>` base-block declaration - would never render and its setup references would resolve against the
 * hidden component. Allowing only `<sw-block extends>` at the top level makes that a loud, structural
 * rule instead of a silent no-op. Whitespace and comments are ignored.
 */
function assertOverrideTemplateTopLevel(children: TemplateChildNode[], templateOffset: number): void {
    children.forEach((node) => {
        if (node.type === NodeTypes.COMMENT) {
            return;
        }

        if (node.type === NodeTypes.TEXT && node.content.trim() === '') {
            return;
        }

        if (isSwBlockExtends(node)) {
            return;
        }

        throw new ShopwareSetupTransformError(
            'An override template may only contain <sw-block extends="..."> blocks at its top level. An override ' +
                'component renders only inside the blocks it extends, so any other top-level markup would never render ' +
                'and its setup references would resolve against the hidden override component. Move it into a ' +
                '<sw-block extends> block.',
            templateOffset + node.loc.start.offset,
        );
    });
}

/**
 * Returns the insertion point immediately after an opening tag name.
 *
 */
function findOpeningTagNameEnd(template: string, elementStart: number): number {
    for (let index = elementStart + 1; index < template.length; index += 1) {
        const character = template[index];

        if (/\s|\/|>/.test(character)) {
            return index;
        }
    }

    throw new ShopwareSetupTransformError('Unable to locate <sw-block> tag name end.', elementStart);
}

/**
 * @private
 */
export { assertOverrideTemplateTopLevel, assertSwBlockAttributes, findOpeningTagNameEnd };
