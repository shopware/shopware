/**
 * Owns the generated bindings of `<sw-block>` elements.
 *
 * The transform generates the block's `data` binding (base mode) and its `#default` slot scope
 * (override mode). Authoring either binding - or a `v-bind` object that could carry them - is
 * rejected, so what a block receives is always exactly what the transform wired.
 */

import { NodeTypes, type TemplateChildNode } from '@vue/compiler-dom';
import type { ShopwareSetupBlock, ShopwareSetupMode } from '../utils/shopware-setup-block';
import { ShopwareSetupTransformError } from '../utils/transform-error';
import {
    type DirectiveNode,
    type ElementNode,
    type SlotMapping,
    type TemplateEdit,
    getDefaultSlotDirective,
    isSwBlockExtends,
    isSwBlockName,
} from './template-references';

/**
 * Rejects the wrong `<sw-block>` kind for the current mode.
 *
 * A base component *declares* blocks with `<sw-block name>`; an override *contributes into* existing
 * blocks with `<sw-block extends>`. The opposite kind in either mode is meaningless, so it is rejected
 * anywhere it appears (top level or nested), not only at the template root.
 */
function assertSwBlockModeIdentity(node: ElementNode, mode: ShopwareSetupMode): void {
    if (mode === 'base' && isSwBlockExtends(node)) {
        throw new ShopwareSetupTransformError(
            '<sw-block extends="..."> is only valid in an override component. A base component declares blocks with ' +
                '<sw-block name="...">.',
            0,
        );
    }

    if (mode === 'override' && isSwBlockName(node)) {
        throw new ShopwareSetupTransformError(
            '<sw-block name="..."> is only valid in a base component. An override contributes into an existing block ' +
                'with <sw-block extends="...">.',
            0,
        );
    }
}

/**
 * Rejects any top-level override template content that is not a `<sw-block extends>` block.
 *
 * An override `.vue` file fundamentally represents "the extension points of a component": it only
 * renders inside the blocks it extends (its hidden boot component has no template of its own that the
 * app shows). So any other top-level markup - plain elements, text, interpolations, or a `<sw-block
 * name>` base-block declaration - would never render and its setup references would resolve against the
 * hidden component. Allowing only `<sw-block extends>` at the top level makes that a loud, structural
 * rule instead of a silent no-op. Whitespace and comments are ignored.
 */
function assertOverrideTemplateTopLevel(children: TemplateChildNode[]): void {
    children.forEach((node) => {
        if (node.type === NodeTypes.COMMENT) {
            return;
        }

        if (node.type === NodeTypes.TEXT && node.content.trim() === '') {
            return;
        }

        if (isSwBlockExtends(node)) {
            return;
        }

        throw new ShopwareSetupTransformError(
            'An override template may only contain <sw-block extends="..."> blocks at its top level. An override ' +
                'component renders only inside the blocks it extends, so any other top-level markup would never render ' +
                'and its setup references would resolve against the hidden override component. Move it into a ' +
                '<sw-block extends> block.',
            0,
        );
    });
}

/**
 * Rejects authored bindings on a `<sw-block>` that the transform generates itself.
 */
function assertNoAuthoredSwBlockBindings(node: ElementNode): void {
    // e.g. `<sw-block extends="..." #default="{ body }">` or a bare `#default`.
    // Also catches the child form `<sw-block extends><template #default="...">`, which otherwise slips
    // past the own-prop check and makes Vue fail with an opaque "Codegen node is missing" error once the
    // transform injects its own generated #default on the element.
    const authoredDefaultSlot =
        getDefaultSlotDirective(node) ??
        node.children.find(
            (child): child is ElementNode =>
                child.type === NodeTypes.ELEMENT &&
                child.tag === 'template' &&
                Boolean(getDefaultSlotDirective(child as ElementNode)),
        );

    if (authoredDefaultSlot) {
        throw new ShopwareSetupTransformError(
            'The default slot scope of <sw-block> is generated by the Shopware setup transform and must not be ' +
                'authored. Reference setup bindings directly instead.',
            0,
        );
    }

    node.props.forEach((prop) => {
        // e.g. `<sw-block name="..." :data="scope">` or `data="scope"`.
        const isDataAttribute = prop.type === NodeTypes.ATTRIBUTE && prop.name === 'data';
        const directive = prop.type === NodeTypes.DIRECTIVE ? (prop as DirectiveNode) : null;
        const isDataBinding = Boolean(
            directive?.name === 'bind' && directive.arg?.isStatic && directive.arg.content === 'data',
        );

        if (isDataAttribute || isDataBinding) {
            throw new ShopwareSetupTransformError(
                'The data binding of <sw-block> is generated by the Shopware setup transform and must not be authored.',
                0,
            );
        }

        // e.g. `<sw-block name="..." v-bind="attrs">` - the object could carry data or slot bindings.
        if (directive?.name === 'bind' && !directive.arg) {
            throw new ShopwareSetupTransformError(
                'v-bind objects are not supported on <sw-block>, because they could carry the generated data or ' +
                    'slot bindings. Use dedicated attributes instead.',
                0,
            );
        }
    });
}

/**
 * Rejects directives on the `<sw-block extends>` element itself.
 *
 * The generated default slot scope only exists inside the block's slot content, so a directive on the
 * element (`v-if`, `v-for`, `@event`, `:attr`, `v-model`, ...) evaluates against the hidden override
 * component's top-level scope instead. Those references are `undefined` there, so the directive either
 * misbehaves silently (e.g. `v-if` never mounts the block, dropping the whole override registration) or
 * cannot be forwarded at all. Only the `extends`/`name` identity binding is allowed.
 */
function assertNoSwBlockExtendsElementDirectives(node: ElementNode): void {
    node.props.forEach((prop) => {
        if (prop.type !== NodeTypes.DIRECTIVE) {
            return;
        }

        const directive = prop as DirectiveNode;
        const isIdentityBinding =
            directive.name === 'bind' &&
            directive.arg?.isStatic &&
            (directive.arg.content === 'extends' || directive.arg.content === 'name');

        if (isIdentityBinding) {
            return;
        }

        throw new ShopwareSetupTransformError(
            `The "${directive.rawName ?? `v-${directive.name}`}" directive is not supported on <sw-block>: its expression ` +
                'would resolve against the hidden override component, not the base component that renders the block. ' +
                'Move the logic into the block content or the override setup.',
            0,
        );
    });
}

/**
 * Returns the insertion point before the closing angle bracket of an opening tag.
 *
 */
function findOpeningTagAttributeEnd(template: string, elementStart: number): number {
    let quote: '"' | "'" | null = null;

    for (let index = elementStart; index < template.length; index += 1) {
        const character = template[index];

        if (quote) {
            if (character === quote) {
                quote = null;
            }

            continue;
        }

        if (character === '"' || character === "'") {
            quote = character;
            continue;
        }

        if (character === '>') {
            return template[index - 1] === '/' ? index - 1 : index;
        }
    }

    throw new ShopwareSetupTransformError('Unable to locate <sw-block> opening tag end.', elementStart);
}

/**
 * Returns the insertion point immediately after an opening tag name.
 *
 */
function findOpeningTagNameEnd(template: string, elementStart: number): number {
    for (let index = elementStart + 1; index < template.length; index += 1) {
        const character = template[index];

        if (/\s|\/|>/.test(character)) {
            return index;
        }
    }

    throw new ShopwareSetupTransformError('Unable to locate <sw-block> tag name end.', elementStart);
}

/**
 * Formats the private slot-scope destructuring entry for one override file namespace.
 *
 */
function createPrivateSlotMapping(namespace: string, localNames: string[]): SlotMapping {
    return {
        sourceKey: '__swOverride',
        source: `__swOverride: { ${namespace}: { ${localNames.join(', ')} } }`,
    };
}

/**
 * Builds the generated `#default` slot scope for one extended sw-block.
 */
function createGeneratedSlotEdit(block: ShopwareSetupBlock, node: ElementNode, mappings: SlotMapping[]): TemplateEdit {
    if (!block.template) {
        throw new ShopwareSetupTransformError('Unable to generate a slot scope without a template block.', 0);
    }

    const sources = mappings.map((mapping) => mapping.source);
    const insertionPoint = findOpeningTagAttributeEnd(block.template.content, node.loc.start.offset);

    return {
        start: block.template.contentStart + insertionPoint,
        end: block.template.contentStart + insertionPoint,
        replacement: ` #default="{ ${sources.join(', ')} }"`,
    };
}

export {
    assertNoAuthoredSwBlockBindings,
    assertNoSwBlockExtendsElementDirectives,
    assertOverrideTemplateTopLevel,
    assertSwBlockModeIdentity,
    createGeneratedSlotEdit,
    createPrivateSlotMapping,
    findOpeningTagNameEnd,
};
