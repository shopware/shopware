/**
 * @sw-package framework
 */

import { NodeTypes, type DirectiveNode, type ElementNode, type TemplateChildNode } from '@vue/compiler-dom';
import type { ShopwareSetupMode } from '../naming';
import { ShopwareSetupTransformError } from '../utils/transform-error';

type BlockIdentity = 'name' | 'extends';

function staticArg(directive: DirectiveNode): string | null {
    return directive.arg?.type === NodeTypes.SIMPLE_EXPRESSION && directive.arg.isStatic ? directive.arg.content : null;
}

function isDefaultSlotDirective(prop: ElementNode['props'][number]): prop is DirectiveNode {
    return prop.type === NodeTypes.DIRECTIVE && prop.name === 'slot' && (!prop.arg || staticArg(prop) === 'default');
}

/**
 * A `<sw-block>` carrying `name` or `extends`, static or bound. The bound form is recognised so that
 * `assertSwBlockAttributes` can reject it.
 */
function isSwBlock(node: TemplateChildNode, identity: BlockIdentity): node is ElementNode {
    return (
        node.type === NodeTypes.ELEMENT &&
        node.tag === 'sw-block' &&
        node.props.some((prop) =>
            prop.type === NodeTypes.ATTRIBUTE
                ? prop.name === identity
                : prop.name === 'bind' && staticArg(prop) === identity,
        )
    );
}

function staticSwBlockAttribute(node: ElementNode, identity: BlockIdentity): string | null {
    const attribute = node.props.find((prop) => prop.type === NodeTypes.ATTRIBUTE && prop.name === identity);

    return attribute?.type === NodeTypes.ATTRIBUTE ? (attribute.value?.content ?? null) : null;
}

/**
 * `<sw-block>` renders its content as a fragment, so any attribute but its static identity would have no
 * element to land on, and a binding would resolve against the wrong component. The `data` binding and
 * the `#default` slot scope are generated.
 */
function assertSwBlockAttributes(node: ElementNode, mode: ShopwareSetupMode): void {
    const identity: BlockIdentity = mode === 'base' ? 'name' : 'extends';
    const wrongIdentity: BlockIdentity = mode === 'base' ? 'extends' : 'name';
    // A default slot on a direct `<template>` child would otherwise surface as Vue's opaque
    // "Codegen node is missing" error.
    const authoredDefaultSlot =
        node.props.find(isDefaultSlotDirective) ??
        node.children.find(
            (child) =>
                child.type === NodeTypes.ELEMENT && child.tag === 'template' && child.props.some(isDefaultSlotDirective),
        );

    if (authoredDefaultSlot) {
        throw new ShopwareSetupTransformError(
            'The default slot scope of <sw-block> is generated by the Shopware setup transform and must not be ' +
                'authored. Reference setup bindings directly instead.',
            authoredDefaultSlot.loc.start.offset,
        );
    }

    const directNamedSlot = node.children.find(
        (child) =>
            child.type === NodeTypes.ELEMENT &&
            child.tag === 'template' &&
            child.props.some(
                (prop) => prop.type === NodeTypes.DIRECTIVE && prop.name === 'slot' && !isDefaultSlotDirective(prop),
            ),
    );

    if (directNamedSlot) {
        throw new ShopwareSetupTransformError(
            'A direct non-default named slot below <sw-block> is not supported. <sw-block> forwards only its ' +
                'default slot; move the <sw-block> inside the named-slot template.',
            directNamedSlot.loc.start.offset,
        );
    }

    node.props.forEach((prop) => {
        const directive = prop.type === NodeTypes.DIRECTIVE ? prop : null;
        const attributeName = prop.type === NodeTypes.ATTRIBUTE ? prop.name : null;
        const boundArg = directive?.name === 'bind' ? staticArg(directive) : null;

        if (attributeName === identity) {
            return;
        }

        if (attributeName === wrongIdentity || boundArg === wrongIdentity) {
            throw new ShopwareSetupTransformError(
                mode === 'base'
                    ? '<sw-block extends="..."> is only valid in an override component. A base component declares ' +
                      'blocks with <sw-block name="...">.'
                    : '<sw-block name="..."> is only valid in a base component. An override contributes into an ' +
                      'existing block with <sw-block extends="...">.',
                prop.loc.start.offset,
            );
        }

        if (attributeName === 'data' || boundArg === 'data') {
            throw new ShopwareSetupTransformError(
                'The data binding of <sw-block> is generated by the Shopware setup transform and must not be authored.',
                prop.loc.start.offset,
            );
        }

        const label = directive ? (directive.rawName ?? `v-${directive.name}`) : (attributeName ?? 'binding');
        throw new ShopwareSetupTransformError(
            `Only a static "${identity}" attribute is allowed on <sw-block>; "${label}" is not supported. ` +
                'sw-block renders its content as a fragment, so other attributes have no effect and their bindings ' +
                'would resolve against the wrong component.',
            prop.loc.start.offset,
        );
    });
}

/**
 * An override renders only inside the blocks it extends, so any other top-level markup would never render.
 */
function assertOverrideTemplateTopLevel(children: TemplateChildNode[]): void {
    children.forEach((node) => {
        if (
            node.type === NodeTypes.COMMENT ||
            (node.type === NodeTypes.TEXT && node.content.trim() === '') ||
            isSwBlock(node, 'extends')
        ) {
            return;
        }

        throw new ShopwareSetupTransformError(
            'An override template may only contain <sw-block extends="..."> blocks at its top level. An override ' +
                'component renders only inside the blocks it extends, so any other top-level markup would never render ' +
                'and its setup references would resolve against the hidden override component. Move it into a ' +
                '<sw-block extends> block.',
            node.loc.start.offset,
        );
    });
}

/**
 * The offset right before the `>` (or `/>`) that closes an element's opening tag.
 */
function openingTagEnd(source: string, element: ElementNode): number {
    let quote: string | null = null;

    for (let index = element.loc.start.offset; index < source.length; index += 1) {
        const character = source[index];

        if (quote) {
            quote = character === quote ? null : quote;
        } else if (character === '"' || character === "'") {
            quote = character;
        } else if (character === '>') {
            return source[index - 1] === '/' ? index - 1 : index;
        }
    }

    throw new ShopwareSetupTransformError('Unable to locate <sw-block> opening tag end.', element.loc.start.offset);
}

/**
 * @private
 */
export { assertOverrideTemplateTopLevel, assertSwBlockAttributes, isSwBlock, openingTagEnd, staticSwBlockAttribute };
