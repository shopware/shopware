/**
 * @sw-package framework
 *
 * Twig blocks of core Administration templates (and the Administration part of the Storefront) that 6.8 removes.
 * Extracted from the `@deprecated tag:v6.8.0` markers and the legacy branches of `feature.isActive('v6.8.0.0')`,
 * then checked by hand. Blocks that 6.8 renames are in `no-renamed-twig-blocks.data.js`.
 *
 * Every group lists the removed blocks of one core component, and the core components that extend it and so render
 * the same blocks. What to use instead:
 * - a block name of the same component: "Override <block> instead.";
 * - `{ use, in }`: "Override <use> in <in> instead.";
 * - `{ extend }`: "… without replacement. Extend <extend> instead.";
 * - `{ tab }`: the tab is an item of the mt-tabs `items` computed now: "Add the tab to the <tab> computed instead.";
 * - `{ hint }`: a sentence of its own;
 * - `null`: "… without replacement.".
 *
 * `shared` maps names that several core components use to those components.
 * The codemod only checks them when it knows which component a template overrides.
 */

