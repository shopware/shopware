/**
 * @sw-package framework
 *
 * Writes the findings of the break check for two revisions as a script that the design pages load:
 *
 *     node_modules/.bin/ts-node --transpileOnly --cwd-mode \
 *         scripts/generate-public-api/compare-page/design-ideas/data/dump-findings.ts <name> <base> <head>
 */
import fs from 'node:fs';
import path from 'node:path';
import { compareCommits } from '../../../break-check/commit-check';
import { ADMINISTRATION_ROOT, currentMajorFlags } from '../../../source/checkout';
import { repositoryOf, resolveCommit } from '../../../source/git-source-tree';

const [name, base, head] = process.argv.slice(2);

if (name === undefined || base === undefined || head === undefined) {
    throw new Error('Usage: dump-findings.ts <name> <base> <head>');
}

const repository = repositoryOf(ADMINISTRATION_ROOT);
const report = {
    base: resolveCommit(repository, base),
    head: resolveCommit(repository, head),
    findings: compareCommits(repository, currentMajorFlags(), base, head),
};

fs.writeFileSync(
    path.join(__dirname, `${name}.js`),
    `/**\n * @sw-package framework\n *\n * Generated by dump-findings.ts.\n */\nwindow.REPORTS = window.REPORTS || {};\nwindow.REPORTS[${JSON.stringify(name)}] = ${JSON.stringify(report)};\n`,
);
