/**
 * @sw-package framework
 *
 * Writes the findings of the break check for two revisions as a script that the design pages load, with the
 * code that the detail of a break shows:
 *
 *     node_modules/.bin/ts-node --transpileOnly --cwd-mode \
 *         scripts/generate-public-api/compare-page/design-ideas/data/dump-findings.ts <name> <base> <head>
 */
import fs from 'node:fs';
import path from 'node:path';
import { explainSourceTrees } from '../../../break-check/break-check';
import type { FindingGroup } from '../../../break-check/finding';
import { ADMINISTRATION_ROOT, currentMajorFlags } from '../../../source/checkout';
import { readSourceTreeAt, repositoryOf, resolveCommit } from '../../../source/git-source-tree';
import { changedCode, fixCode } from '../../finding-code';
import type { Finding } from '../src/shared/report';

const [name, base, head] = process.argv.slice(2);

if (name === undefined || base === undefined || head === undefined) {
    throw new Error('Usage: dump-findings.ts <name> <base> <head>');
}

/** The groups whose findings the pages show one at a time. The details of the other groups stay out of the file. */
const WITH_DETAIL: readonly FindingGroup[] = [
    'Break',
    'Allowed',
];

const repository = repositoryOf(ADMINISTRATION_ROOT);
const commits = { base: resolveCommit(repository, base), head: resolveCommit(repository, head) };
const before = readSourceTreeAt(repository, commits.base);
const after = readSourceTreeAt(repository, commits.head);
const findings = explainSourceTrees(before, after, currentMajorFlags()).map(
    (finding): Finding =>
        WITH_DETAIL.includes(finding.group)
            ? {
                  ...finding,
                  code: { changed: changedCode(finding, before, after), fix: fixCode(finding, before, after) },
              }
            : { ...finding, detail: {} },
);

fs.writeFileSync(
    path.join(__dirname, `${name}.js`),
    `/**\n * @sw-package framework\n *\n * Generated by dump-findings.ts.\n */\nwindow.REPORTS = window.REPORTS || {};\nwindow.REPORTS[${JSON.stringify(name)}] = ${JSON.stringify({ ...commits, findings })};\n`,
);
