/**
 * @sw-package framework
 *
 * What the snapshot says about the global `Shopware` object and the objects below it.
 */
import type { SourceTree } from '../../source/source-tree';
import { snapshotOf } from '../../snapshot/snapshot';
import { OPTIONS, treeOf } from '../../testing/example-components';
import { GLOBAL_REPORT, SHOPWARE_FILE, shopwareTree } from '../../testing/example-globals';
import { MAIN } from '../../testing/example-services';

const FACTORY = 'src/core/factory/example.factory.ts';

const FACTORY_IMPORT = "import ExampleFactory from 'src/core/factory/example.factory';";

const THING_IMPORT = "import { createThing } from 'src/core/factory/example.factory';";

function files(tree: SourceTree): Record<string, string> {
    return snapshotOf(tree, OPTIONS).files;
}

/** The outline of each unit in the report of the Shopware object, by the name of the unit, without empty lines. */
function outlines(tree: SourceTree): Record<string, string[]> {
    const [, block = ''] = /```text\n([\s\S]*?)\n```/.exec(files(tree)[GLOBAL_REPORT] ?? '') ?? [];
    const units = block.split(/\n\n(?=global )/).filter((unit) => unit !== '');

    return Object.fromEntries(
        units.map((unit) => {
            const [header, ...lines] = unit.split('\n').filter((line) => line !== '');

            return [header.split('  ')[0].replace('global ', ''), [header, ...lines]];
        }),
    );
}

/** The lines of the sections of one unit, which follow its three header lines. */
function sections(tree: SourceTree, unit = 'Shopware'): string[] {
    return (outlines(tree)[unit] ?? ['missing unit']).slice(3);
}

describe('scripts/generate-public-api/read/globals/global-units', () => {
    describe('the Shopware object', () => {
        it('lists the members of its class: values, getters, and functions with the signature of their declaration', () => {
            const tree = shopwareTree(
                [
                    "    public Defaults = { versionId: '0fa9' };",
                    '    public Service = ExampleFactory.getByName;',
                    '    public Limit: number = 25;',
                    '    public get Context() { return 1; }',
                    '    static #cache = new Map();',
                    '    private secret = 1;',
                ].join('\n'),
                { [FACTORY]: 'function getByName(name: string): unknown {}\nexport default { getByName };' },
                FACTORY_IMPORT,
            );

            expect(outlines(tree).Shopware).toEqual([
                'global Shopware  public  ts  instance',
                '  registered src/core/shopware.ts',
                '  source src/core/shopware.ts',
                'properties',
                '  Context: any',
                '  Defaults: any',
                '  Limit: number',
                'methods',
                '  Service(name: string): unknown',
            ]);
        });

        it('has no units in a tree without the file that builds the object, and rejects that file without the class', () => {
            expect(JSON.parse(files(treeOf({ [MAIN]: '' }))['index.json'])).toMatchObject({ globals: {} });
            expect(() => files(treeOf({ [SHOPWARE_FILE]: 'export const ShopwareInstance = {};' }))).toThrow(
                'src/core/shopware.ts no longer builds Shopware as an instance of a class, so the snapshot cannot read the object.',
            );
        });

        it('writes all units into the report of the file that builds the object, with an index entry each', () => {
            const generated = files(shopwareTree('    public Example = { load() {} };'));

            expect(Object.keys(generated).sort()).toEqual([GLOBAL_REPORT, 'index.json']);
            expect(generated[GLOBAL_REPORT].split('\n').slice(0, 5)).toEqual([
                '# Globals of src/core/shopware.ts',
                '',
                '<!-- Generated by `composer admin:generate-public-api`. Do not edit. -->',
                '',
                'API report of the globals of `src/core/shopware.ts` in both flag states.',
            ]);
            expect(JSON.parse(generated['index.json'])).toMatchObject({
                globals: {
                    Shopware: { file: 'core/shopware', visibility: 'public' },
                    'Shopware.Example': { file: 'core/shopware', visibility: 'public' },
                },
            });
        });
    });

    describe('the objects below it', () => {
        it('gives an object literal, an instance, a class with static members and what a getter returns a unit each', () => {
            const tree = shopwareTree(
                [
                    '    public Module = { register: ExampleFactory.register };',
                    '    public Application = application;',
                    '    public Feature = Feature;',
                    '    public get Context() { return useContext(); }',
                    '    public Store = Store.instance;',
                ].join('\n'),
                { [FACTORY]: 'function register(name: string): boolean {}\nexport default { register };' },
                [
                    FACTORY_IMPORT,
                    'class Bootstrapper { start(): void {} }',
                    'const application = new Bootstrapper();',
                    'class Feature { static isActive(flag: string): boolean {} check() {} }',
                    'function useContext() { return { ...toRefs(state), setLanguage(id: string) {} }; }',
                    'const state = reactive({ api: {} });',
                    'class Store { static get instance(): Store { return Store.#instance; } get(id: string) {} }',
                ].join('\n'),
            );

            expect(
                Object.fromEntries(
                    Object.entries(outlines(tree)).map(([unit, lines]) => [unit, [lines[0], ...lines.slice(3)]]),
                ),
            ).toEqual({
                Shopware: [
                    'global Shopware  public  ts  instance',
                    'properties',
                    '  Application: any',
                    '  Context: any',
                    '  Feature: any',
                    '  Module: any',
                    '  Store: any',
                ],
                'Shopware.Application': ['global Shopware.Application  public  ts  instance', 'methods', '  start(): void'],
                'Shopware.Context': [
                    'global Shopware.Context  public  ts  object',
                    'properties',
                    '  api: any',
                    'methods',
                    '  setLanguage(id: string): any',
                ],
                'Shopware.Feature': [
                    'global Shopware.Feature  public  ts  class',
                    'methods',
                    '  isActive(flag: string): boolean',
                ],
                'Shopware.Module': [
                    'global Shopware.Module  public  ts  object',
                    'methods',
                    '  register(name: string): boolean',
                ],
                'Shopware.Store': ['global Shopware.Store  public  ts  instance', 'methods', '  get(id: string): any'],
            });
        });

        it('follows a member that an object takes from a namespace import', () => {
            const tree = shopwareTree(
                '    public Utils = { string: { camelCase: stringUtils.camelCase } };',
                { 'src/core/service/utils/string.utils.ts': 'export function camelCase(value: string): string {}' },
                "import * as stringUtils from 'src/core/service/utils/string.utils';",
            );

            expect(sections(tree, 'Shopware.Utils.string')).toEqual(['methods', '  camelCase(value: string): string']);
        });

        it('names the file that declares the object as its source', () => {
            const tree = shopwareTree(
                '    public Utils = utils;',
                { 'src/core/service/util.service.ts': 'export default { createId() {} };' },
                "import utils from 'src/core/service/util.service';",
            );

            expect(outlines(tree)['Shopware.Utils'].slice(0, 3)).toEqual([
                'global Shopware.Utils  public  ts  object',
                '  registered src/core/shopware.ts',
                '  source src/core/service/util.service.ts',
            ]);
        });

        it('follows the objects two levels down and lists what is deeper as a property', () => {
            const tree = shopwareTree(
                '    public Utils = { string: { camelCase() {}, cases: { upper() {} } }, empty: {} };',
            );

            expect(Object.keys(outlines(tree))).toEqual([
                'Shopware',
                'Shopware.Utils',
                'Shopware.Utils.empty',
                'Shopware.Utils.string',
            ]);
            expect(sections(tree, 'Shopware.Utils.empty')).toEqual([]);
            expect(sections(tree, 'Shopware.Utils')).toEqual(['properties', '  empty: any', '  string: any']);
            expect(sections(tree, 'Shopware.Utils.string')).toEqual([
                'properties',
                '  cases: any',
                'methods',
                '  camelCase(): any',
            ]);
        });
    });

    describe('visibility and markers', () => {
        it('marks a member with a private tag, and everything below it', () => {
            const tree = shopwareTree(
                '    /** @private */\n    public _private = { helpers: { format() {} } };\n    public Defaults = {};',
            );

            expect(sections(tree)).toEqual(['properties', '  Defaults: any', '  _private: any  [private]']);
            expect(outlines(tree)['Shopware._private'][0]).toBe('global Shopware._private  private  ts  object  [private]');
            expect(outlines(tree)['Shopware._private.helpers']).toEqual([
                'global Shopware._private.helpers  private  ts  object  [private]',
                '  registered src/core/shopware.ts  [private]',
                '  source src/core/shopware.ts  [private]',
                '  visibility-source parent  [private]',
                'methods',
                '  format(): any  [private]',
            ]);
        });

        it.each([
            ['its member', '    /** @private */\n    public Telemetry = { track() {} };', ''],
            ['its declaration', '    public Telemetry = Telemetry;', '/** @private */\nconst Telemetry = { track() {} };'],
            [
                'its class',
                '    public Telemetry = Telemetry;',
                '/** @private */\nclass Tracker { track() {} }\nconst Telemetry = new Tracker();',
            ],
        ])('names its own comment as the source of a private object when %s carries the tag', (_, member, before) => {
            const tree = shopwareTree(`${member}\n    public Defaults = {};`, {}, before);

            expect(outlines(tree)['Shopware.Telemetry']).toContain('  visibility-source export  [private]');
        });

        it('names the object above as the source of a private object that a private class holds without a public tag', () => {
            const tree = shopwareTree(
                '    public Application = application;',
                {},
                [
                    '/** @private */',
                    'class Bootstrapper {',
                    '    /** @public */',
                    '    getContainer() {}',
                    '    helpers = { format() {} };',
                    '}',
                    'const application = new Bootstrapper();',
                ].join('\n'),
            );

            expect(outlines(tree)['Shopware.Application.helpers']).toContain('  visibility-source parent  [private]');
        });

        it('takes the private tag and the markers of the declaration that a member names', () => {
            const tree = shopwareTree(
                '    public Example = { build: ExampleFactory.build, load: ExampleFactory.load, Helper };',
                {
                    [FACTORY]: [
                        '/** @private */',
                        'function build() {}',
                        '/** @deprecated tag:v6.8.0 - Use find instead. */',
                        'function load() {}',
                        'export default { build, load };',
                    ].join('\n'),
                },
                `${FACTORY_IMPORT}\n/** @private */\nconst Helper = { format() {} };`,
            );

            expect(sections(tree, 'Shopware.Example')).toEqual([
                'properties',
                '  Helper: any  [private]',
                'methods',
                '  build(): any  [private]',
                '  load(): any  [deprecated tag:v6.8.0]',
            ]);
            expect(outlines(tree)['Shopware.Example.Helper'][0]).toBe(
                'global Shopware.Example.Helper  private  ts  object  [private]',
            );
        });

        it('does not take the private tag of a getter that a member names, because the member holds what it returns', () => {
            const tree = shopwareTree(
                '    public Store = Store.instance;',
                {},
                [
                    'class Store {',
                    '    /** @private */',
                    '    static get instance(): Store { return Store.#instance; }',
                    '    get(id: string) {}',
                    '}',
                ].join('\n'),
            );

            expect(sections(tree)).toEqual(['properties', '  Store: any']);
            expect(outlines(tree)['Shopware.Store']).toEqual([
                'global Shopware.Store  public  ts  instance',
                '  registered src/core/shopware.ts',
                '  source src/core/shopware.ts',
                'methods',
                '  get(id: string): any',
            ]);
        });

        it('takes the private tag of the member that holds an object, and not the one of the class around that member', () => {
            const store = (registry: string): SourceTree =>
                shopwareTree('    public Store = Registry.store;', {}, `class Store { get(id: string) {} }\n${registry}`);

            expect(sections(store('/** @private */\nclass Registry {\n    static store = new Store();\n}'))).toEqual([
                'properties',
                '  Store: any',
            ]);
            expect(sections(store('class Registry {\n    /** @private */\n    static store = new Store();\n}'))).toEqual([
                'properties',
                '  Store: any  [private]',
            ]);
        });

        it('takes the private tag of a function from the member that declares it, however the member writes the function', () => {
            const tree = shopwareTree(
                '    public Example = { parse: helpers.parse, format: helpers.format, print: helpers.print };',
                {},
                [
                    'const helpers = {',
                    '    /** @private */',
                    '    parse() {},',
                    '    /** @private */',
                    '    format: function () {},',
                    '    /** @private */',
                    '    print: () => {},',
                    '};',
                ].join('\n'),
            );

            expect(sections(tree, 'Shopware.Example')).toEqual([
                'methods',
                '  format(): any  [private]',
                '  parse(): any  [private]',
                '  print(): any  [private]',
            ]);
        });

        it.each([
            ['the function that returns it', '/** @private */\nexport function createThing() { return { run() {} }; }'],
            [
                'the constant that holds it',
                '/** @private */\nconst thing = { run() {} };\nexport function createThing() { return thing; }',
            ],
        ])('takes the private tag of an object from %s, as a service of that object does', (_, factory) => {
            const tree = shopwareTree(
                '    public Thing = createThing();',
                {
                    [FACTORY]: factory,
                    [MAIN]: `${THING_IMPORT}\nShopware.Application.addServiceProvider('thing', () => createThing());`,
                },
                THING_IMPORT,
            );

            expect(sections(tree)).toEqual(['properties', '  Thing: any  [private]']);
            expect(outlines(tree)['Shopware.Thing'][0]).toBe('global Shopware.Thing  private  ts  object  [private]');
            expect(JSON.parse(files(tree)['index.json'])).toMatchObject({
                services: { thing: { visibility: 'private' } },
            });
        });

        it('does not take the private tag above a list of exports, which says nothing about one of its names', () => {
            const tree = shopwareTree(
                '    public Example = { build, Kind };',
                { [FACTORY]: 'function build() {}\nenum Kind { A }\n\n/** @private */\nexport { build, Kind };' },
                "import { build, Kind } from 'src/core/factory/example.factory';",
            );

            expect(sections(tree, 'Shopware.Example')).toEqual([
                'properties',
                '  Kind: any',
                'methods',
                '  build(): any',
            ]);
        });

        it('shows a marker once that the member and the object it holds both carry', () => {
            const tree = shopwareTree(
                '    public Example = { Helper };',
                {},
                '/** @deprecated tag:v6.8.0 - Use Utils instead. */\nconst Helper = { format() {} };',
            );

            expect(outlines(tree)['Shopware.Example.Helper'][0]).toBe(
                'global Shopware.Example.Helper  public  ts  object  [deprecated tag:v6.8.0]',
            );
        });

        it('keeps the object of a private class private, and with it the member that holds it', () => {
            const tree = shopwareTree(
                '    public Application = application;',
                {},
                '/** @private */\nclass Bootstrapper { start() {} }\nconst application = new Bootstrapper();',
            );

            expect(sections(tree)).toEqual(['properties', '  Application: any  [private]']);
            expect(outlines(tree)['Shopware.Application']).toEqual([
                'global Shopware.Application  private  ts  instance  [private]',
                '  registered src/core/shopware.ts  [private]',
                '  source src/core/shopware.ts  [private]',
                '  visibility-source export  [private]',
                'methods',
                '  start(): any  [private]',
            ]);
        });

        it('makes the object of a private class public for the members that carry a public tag', () => {
            const tree = shopwareTree(
                '    public Application = application;',
                {},
                [
                    '/** @private */',
                    'class Bootstrapper {',
                    '    /**',
                    '     * Returns a container.',
                    '     *',
                    '     * @public',
                    '     */',
                    '    getContainer(name: string) {}',
                    '    start() {}',
                    '}',
                    'const application = new Bootstrapper();',
                ].join('\n'),
            );

            expect(sections(tree)).toEqual(['properties', '  Application: any']);
            expect(outlines(tree)['Shopware.Application']).toEqual([
                'global Shopware.Application  public  ts  instance',
                '  registered src/core/shopware.ts',
                '  source src/core/shopware.ts',
                'methods',
                '  getContainer(name: string): any',
                '  start(): any  [private]',
            ]);
        });

        it('shows the markers of a member on the member and on the unit below it', () => {
            const tree = shopwareTree(
                '    /** @deprecated tag:v6.8.0 - Use Store instead. */\n    public State = { commit() {} };',
            );

            expect(sections(tree)).toEqual(['properties', '  State: any  [deprecated tag:v6.8.0]']);
            expect(outlines(tree)['Shopware.State'][0]).toBe(
                'global Shopware.State  public  ts  object  [deprecated tag:v6.8.0]',
            );
        });
    });
});
