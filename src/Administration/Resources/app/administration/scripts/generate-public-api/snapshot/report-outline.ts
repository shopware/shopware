/**
 * @sw-package framework
 *
 * What every report is made of: the lines and sections of the outline of a unit, the markers that follow a
 * line, and the file around the outlines.
 */
import type { Marker } from '../../../eslint-rules/deprecation-rules/utils/api-markers';
import { byCodePoint } from '../helpers/code-point-order';
import type { FlagContext, FlagStates } from '../model/flag-states';

/** @private */
export const GENERATE_COMMAND = 'composer admin:generate-public-api';

const FORMAT_DOCUMENT = 'technical-docs/11-code-quality/03-public-api-snapshot.md';

/**
 * @private
 *
 * A line of the outline. Its markers follow the text in brackets, without the brackets here.
 */
export interface Line {
    text: string;
    markers: string[];
}

/** @private */
export interface Section {
    heading: string;
    lines: Line[];
}

/** @private */
export function line(text: string, ...markers: (string | null)[]): Line {
    return { text, markers: markers.filter((marker) => marker !== null) };
}

/**
 * @private
 *
 * How a line shows the `@deprecated` and `@bc-change` markers of its element. The message of a marker is left
 * out, and of its keys only the parameter it names is shown.
 */
export function markerLabels(markers: Marker[]): string[] {
    return markers.map((marker) =>
        marker.tag === 'deprecated'
            ? `deprecated tag:${marker.version}`
            : [
                  'bc-change',
                  marker.kind,
                  marker.version,
                  marker.parameters.parameter,
              ]
                  .filter(Boolean)
                  .join(' '),
    );
}

/**
 * @private
 *
 * The marker of an element that exists in one flag state only, without brackets.
 */
export function flagStateMarker(states: FlagStates, flags: FlagContext): string | null {
    if (states.current === states.major) {
        return null;
    }

    return `${states.current ? 'until' : 'from'} ${flags.majorVersion}`;
}

/**
 * @private
 *
 * What the generator could not read of a unit, so a reviewer sees that its sections may miss a member.
 */
export function notesSection(notes: string[]): Section {
    return { heading: 'notes', lines: [...new Set(notes)].sort(byCodePoint).map((note) => line(`  ${note}`)) };
}

/**
 * @private
 *
 * The outline of one unit: its header, then every section that has lines. Every line of a private unit carries
 * `[private]` as its last marker. The headings of the sections belong to no element, so they carry none.
 */
export function printOutline(header: Line[], sections: Section[], isPrivate: boolean): string[] {
    const unitMarkers = isPrivate ? ['private'] : [];
    const print = ({ text, markers }: Line): string => {
        const shown = [
            ...markers,
            ...unitMarkers,
        ];

        return shown.length > 0 ? `${text}  ${shown.map((marker) => `[${marker}]`).join(' ')}` : text;
    };

    return [
        ...header.map(print),
        ...sections
            .filter(({ lines }) => lines.length > 0)
            .flatMap(({ heading, lines }) => [
                '',
                heading,
                ...lines.map(print),
            ]),
    ];
}

/**
 * @private
 *
 * A report file: its title, what it is the report of, and the outlines of its units in one block.
 */
export function printReportFile(title: string, subject: string, outlines: string[][]): string {
    return [
        `# ${title}`,
        '',
        `<!-- Generated by \`${GENERATE_COMMAND}\`. Do not edit. -->`,
        '',
        `API report of ${subject} in both flag states.`,
        `Line format and markers: \`${FORMAT_DOCUMENT}\`.`,
        '```text',
        ...outlines.flatMap((outline, position) => (position === 0 ? outline : ['', ...outline])),
        '```',
        '',
    ].join('\n');
}
