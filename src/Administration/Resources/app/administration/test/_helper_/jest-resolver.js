const url = require('url');
const fs = require('fs');
const path = require('path');

const VIRTUAL_MODULE = /^shopware:[a-z]+(\/.+)?$/;
const RESOLVER = path.join(__dirname, 'virtual-shopware-modules', 'resolve-module.js');
const STUB_DIR = path.join(__dirname, '..', '..', 'node_modules', '.cache', 'shopware-virtual-modules');

/**
 * Writes the stub Jest loads for one `shopware:*` specifier and returns its path.
 *
 * Jest resolves a request to a file on disk, and there are 90-odd specifiers, so they are created on
 * demand instead of being checked in or generated by a setup step.
 */
function stubFor(specifier) {
    const file = path.join(STUB_DIR, `${specifier.replace(/[:/]/g, '__')}.js`);
    const contents = `module.exports = require(${JSON.stringify(RESOLVER)})(${JSON.stringify(specifier)});\n`;

    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== contents) {
        fs.mkdirSync(STUB_DIR, { recursive: true });

        // Written under a worker-unique name and renamed, so parallel workers never read a partial stub.
        const pending = `${file}.${process.pid}.tmp`;

        fs.writeFileSync(pending, contents);
        fs.renameSync(pending, file);
    }

    return file;
}

module.exports = (request, options) => {
    if (VIRTUAL_MODULE.test(request)) {
        return stubFor(request);
    }

    // Remove any query parameters in the request path
    // (e.g. ?worker, which Vite uses for worker imports)
    if (request.includes('?')) {
        return options.defaultResolver(url.parse(request).pathname, options);
    }

    return options.defaultResolver(request, options);
};
