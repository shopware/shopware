<?php declare(strict_types=1);

namespace Shopware\Core\Content\ProductExport\Service;

use League\Flysystem\FilesystemException;
use League\Flysystem\FilesystemOperator;
use League\Flysystem\UnableToDeleteFile;
use Psr\Clock\ClockInterface;
use Shopware\Core\Content\ProductExport\ProductExportEntity;
use Shopware\Core\Content\ProductExport\Struct\ExportBehavior;
use Shopware\Core\Framework\Log\Package;
use Shopware\Core\Framework\Uuid\Uuid;

#[Package('inventory')]
class ProductExportFileHandler implements ProductExportFileHandlerInterface
{
    /**
     * @internal
     */
    public function __construct(
        private readonly FilesystemOperator $fileSystem,
        private readonly string $exportDirectory,
        private readonly ClockInterface $clock,
    ) {
    }

    public function getFilePath(ProductExportEntity $productExport, bool $partialGeneration = false): string
    {
        $filePath = \sprintf(
            '%s/%s',
            $this->exportDirectory,
            $productExport->getFileName()
        );

        if ($partialGeneration) {
            $filePath .= '.partial';
        }

        return $filePath;
    }

    public function writeProductExportContent(string $content, string $filePath, bool $append = false): bool
    {
        if (!$append) {
            $this->replaceFile($filePath, $content);

            return true;
        }

        $existingContent = '';
        if ($this->fileSystem->fileExists($filePath)) {
            $existingContent = $this->fileSystem->read($filePath);
        }

        $this->fileSystem->write(
            $filePath,
            $existingContent . $content
        );

        return true;
    }

    public function isValidFile(string $filePath, ExportBehavior $behavior, ProductExportEntity $productExport): bool
    {
        if (!$this->fileSystem->fileExists($filePath)) {
            return false;
        }

        // Forcing generation (e.g. `product-export:generate --force`) must always regenerate the
        // file, even for exports that are otherwise only generated by the scheduler.
        if ($behavior->ignoreCache()) {
            return false;
        }

        return $productExport->isGenerateByCronjob() || !$this->isCacheExpired($productExport);
    }

    public function finalizePartialProductExport(string $partialFilePath, string $finalFilePath, string $headerContent, string $footerContent): bool
    {
        $content = $this->fileSystem->read($partialFilePath);

        try {
            $this->fileSystem->delete($partialFilePath);
        } catch (UnableToDeleteFile) {
            return false;
        }

        $this->replaceFile($finalFilePath, $headerContent . $content . $footerContent);

        return true;
    }

    private function replaceFile(string $filePath, string $content): void
    {
        $temporaryFilePath = $filePath . '.' . Uuid::randomHex() . '.tmp';

        try {
            $this->fileSystem->write($temporaryFilePath, $content);
            $this->fileSystem->move($temporaryFilePath, $filePath);
        } catch (FilesystemException $exception) {
            try {
                $this->fileSystem->delete($temporaryFilePath);
            } catch (UnableToDeleteFile) {
            }

            throw $exception;
        }
    }

    private function isCacheExpired(ProductExportEntity $productExport): bool
    {
        if ($productExport->getGeneratedAt() === null) {
            return true;
        }

        $expireTimestamp = $productExport->getGeneratedAt()->getTimestamp() + $productExport->getInterval();

        return $this->clock->now()->getTimestamp() > $expireTimestamp;
    }
}
